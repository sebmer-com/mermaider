import { JSDOM } from "jsdom";
import { stableId } from "./util.js";
import type { Diagram, Evidence } from "./types.js";

const id = (s: string) => stableId("n", s);
// Mermaid accepts numeric entity escapes inside labels, including quotes and brackets.
const label = (s: string) =>
  s
    .replace(/[\r\n]+/g, " ")
    .replace(/[&<>"#{}\[\]`\\]/g, (c) => `#${c.charCodeAt(0)};`);
const sequenceLabel = (s: string) =>
  s
    .replace(/[\r\n]+/g, " ")
    .replace(/[&<>"#;:{}\[\]`\\]/g, (c) => `#${c.charCodeAt(0)};`);
const identifier = (s: string) =>
  s.replace(/[^a-zA-Z0-9_]/g, "_").replace(/^[0-9]/, "_$&") || "field";
const order = <T extends { id: string }>(xs: T[]) =>
  [...xs].sort((a, b) => a.id.localeCompare(b.id, "en"));

export function renderMermaid(diagram: Diagram): string {
  const nodes = order(diagram.nodes),
    edges = order(diagram.edges);
  const out: string[] = [];
  if (diagram.syntax === "sequence") {
    out.push("sequenceDiagram");
    for (const n of nodes)
      out.push(`    participant ${id(n.id)} as ${sequenceLabel(n.label)}`);
    for (const step of diagram.steps || [])
      out.push(
        `    ${id(step.from)}${step.kind === "reply" ? "-->>" : "->>"}${id(step.to)}: ${sequenceLabel(step.label)}`,
      );
  } else if (diagram.syntax === "state") {
    out.push("stateDiagram-v2");
    for (const n of nodes)
      out.push(`    state "${label(n.label)}" as ${id(n.id)}`);
    for (const e of edges)
      out.push(
        `    ${id(e.from)} --> ${id(e.to)}${e.label ? `: ${sequenceLabel(e.label)}` : ""}`,
      );
  } else if (diagram.syntax === "er") {
    out.push("erDiagram");
    for (const n of nodes) {
      out.push(`    ${id(n.id)}["${label(n.label)}"]`);
      if (n.attributes?.length) {
        out[out.length - 1] += " {";
        for (const a of [...n.attributes].sort((a, b) =>
          a.name.localeCompare(b.name, "en"),
        ))
          out.push(
            `        ${identifier(a.type)} ${identifier(a.name)}${a.key ? ` ${a.key}` : ""}`,
          );
        out.push("    }");
      }
    }
    for (const e of edges)
      out.push(
        `    ${id(e.from)} ${e.cardinality?.from || "}o"}--${e.cardinality?.to || "||"} ${id(e.to)} : "${label(e.label || "references")}"`,
      );
  } else {
    out.push(
      `flowchart ${diagram.direction || (diagram.family === "process" ? "TD" : "LR")}`,
    );
    for (const n of nodes) out.push(`    ${id(n.id)}["${label(n.label)}"]`);
    for (const e of edges)
      out.push(
        `    ${id(e.from)} -->${e.label ? `|"${label(e.label)}"|` : ""} ${id(e.to)}`,
      );
  }
  return out.join("\n") + "\n";
}

let parser: Promise<typeof import("mermaid")> | undefined;
export async function validateMermaid(text: string): Promise<void> {
  if (!parser) {
    const dom = new JSDOM("<!doctype html><html><body></body></html>");
    // Mermaid's parser sanitizes labels through DOMPurify, even without rendering.
    Object.assign(globalThis, {
      window: dom.window,
      document: dom.window.document,
    });
    parser = import("mermaid");
  }
  const { default: mermaid } = await parser;
  mermaid.initialize({
    startOnLoad: false,
    securityLevel: "strict",
    suppressErrorRendering: true,
  });
  await mermaid.parse(text);
}

export function diagramEvidence(d: Diagram): Evidence[] {
  const sources = [
    ...d.nodes.flatMap((n) => n.evidence),
    ...d.edges.flatMap((e) => e.evidence),
    ...(d.steps || []).flatMap((s) => s.evidence),
  ];
  // Preserve conflicting hashes: every assertion must pass evidence validation.
  return [
    ...new Map(
      sources.map((e) => [
        `${e.path}\0${e.symbol || ""}\0${e.line || ""}\0${e.sha256 || ""}`,
        e,
      ]),
    ).values(),
  ].sort(
    (a, b) =>
      a.path.localeCompare(b.path, "en") ||
      (a.line || 0) - (b.line || 0) ||
      (a.symbol || "").localeCompare(b.symbol || "", "en"),
  );
}
export function renderMarkdown(
  d: Diagram,
  mermaid: string,
  sourceLink: (e: Evidence) => string,
  projected = false,
): string {
  const lines = [
    `# ${d.title}`,
    "",
    `Generated by Mermaider. View: **${d.context}**. Basis: **${d.provenance === "curated" ? "agent-reviewed semantic model" : "declared source structure"}**.`,
    "",
  ];
  if (projected)
    lines.push(
      "This view is an explicitly selected subset of the source model.",
      "",
    );
  if (d.diagnostics?.length) {
    lines.push("## Coverage notes", "");
    for (const x of d.diagnostics) lines.push(`- **${x.code}**: ${x.message}`);
    lines.push("");
  }
  lines.push("```mermaid", mermaid.trimEnd(), "```", "", "## Sources", "");
  for (const e of diagramEvidence(d))
    lines.push(
      `- [${e.path}${e.symbol ? ` · ${e.symbol}` : ""}${e.line ? `:${e.line}` : ""}](${sourceLink(e)})`,
    );
  lines.push(
    "",
    "Freshness checks confirm the recorded source evidence and generated output. They do not establish live deployment or prove every semantic interpretation.",
    "",
  );
  return lines.join("\n");
}
