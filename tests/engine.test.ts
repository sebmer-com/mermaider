async function fixture(t: any) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "mermaider-engine-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  execFileSync("git", ["init", "-q", root]);
  const write = async (p: string, value: string | object) => {
    await fs.mkdir(path.dirname(path.join(root, p)), { recursive: true });
    await fs.writeFile(
      path.join(root, p),
      typeof value === "string" ? value : stableJson(value),
    );
  };
  await write("package.json", {
    name: "sample",
    dependencies: { hello: "1.0.0" },
  });
  await write(".gitignore", "node_modules/\n");
  return { root, write };
}
test("identical runs are byte-identical and output-only commits do not invalidate inputs", async (t) => {
  const { root } = await fixture(t);
  await initialize(root, { families: ["dependencies"] });
  assert.equal((await update(root)).ok, true);
  const before = await fs.readFile(
    path.join(root, ".mermaider/manifest.json"),
    "utf8",
  );
  const again = await update(root);
  assert.equal(again.ok, true);
  assert.deepEqual(again.changed, []);
  const html = await fs.readFile(
    path.join(root, "docs/mermaider/index.html"),
    "utf8",
  );
  assert.match(html, /<html lang="en">/);
  assert.match(html, /Copyright \(c\) 2014 - 2022 Knut Sveidqvist/);
  assert(!/<script[^>]+src=/.test(html));
  assert.equal(
    await fs.readFile(path.join(root, ".mermaider/manifest.json"), "utf8"),
    before,
  );
  execFileSync("git", ["-C", root, "add", "."]);
  execFileSync("git", [
    "-C",
    root,
    "-c",
    "user.name=Test",
    "-c",
    "user.email=test@example.test",
    "commit",
    "-qm",
    "source and diagrams",
  ]);
  assert.equal((await check(root)).ok, true);
  assert.equal((await getHookStatus(root)).current, true);
});
test("new relevant files invalidate freshness while edited generated files are never overwritten", async (t) => {
  const { root, write } = await fixture(t);
  await initialize(root, { families: ["dependencies"] });
  await update(root);
  await write("new.ts", "export const newBehavior = true;");
  assert.equal((await getHookStatus(root)).current, false);
  assert.equal((await check(root)).ok, false);
  assert.equal((await update(root)).ok, true);
  const config = JSON.parse(
    await fs.readFile(path.join(root, ".mermaider/config.json"), "utf8"),
  );
  const output = path.join(
    root,
    config.outputDir,
    config.diagrams[0].id + ".md",
  );
  await fs.appendFile(output, "\nA human note.\n");
  assert.equal((await getHookStatus(root)).current, false);
  const result = await update(root);
  assert.equal(result.ok, false);
  assert(result.diagnostics.some((d) => d.code === "OUTPUT_MODIFIED"));
  assert.match(await fs.readFile(output, "utf8"), /A human note/);
});
test("managed regions preserve surrounding prose, reject edits inside owned region, and support fresh adoption", async (t) => {
  const { root, write } = await fixture(t);
  const candidate = (await discover(root)).diagrams[0];
  await write(".mermaider/config.json", {
    version: 1,
    diagrams: [
      {
        id: candidate.id,
        output: { markdown: "docs/architecture.md", block: "deps" },
      },
    ],
  });
  await write(
    "docs/architecture.md",
    "# Human heading\n\n<!-- mermaider:deps:start -->\n<!-- mermaider:deps:end -->\n\nHuman footer.\n",
  );
  assert.equal((await update(root)).ok, true);
  let content = await fs.readFile(
    path.join(root, "docs/architecture.md"),
    "utf8",
  );
  assert(content.startsWith("# Human heading"));
  assert(content.endsWith("Human footer.\n"));
  await write(
    "docs/architecture.md",
    content.replace("Human footer.", "Revised footer."),
  );
  assert.equal((await update(root)).ok, true);
  assert.match(
    await fs.readFile(path.join(root, "docs/architecture.md"), "utf8"),
    /Revised footer/,
  );
  content = await fs.readFile(path.join(root, "docs/architecture.md"), "utf8");
  await write(
    "docs/architecture.md",
    content.replace("Generated by Mermaider.", "Manually changed."),
  );
  assert.equal((await update(root)).ok, false);
});
test("curated evidence outside discovery globs still invalidates hooks and requires reviewed hashes", async (t) => {
  const { root, write } = await fixture(t);
  await write("src/auth.ts", 'export function signup() { return "ok"; }\n');
  const evidence = await evidenceFor(root, "src/auth.ts", "signup");
  const diagram: Diagram = {
    id: "signup",
    title: "Sign up",
    family: "process",
    syntax: "flowchart",
    provenance: "curated",
    context: "implemented",
    nodes: [
      { id: "user", label: "User", evidence: [evidence] },
      { id: "app", label: "Application", evidence: [evidence] },
    ],
    edges: [
      {
        id: "request",
        from: "user",
        to: "app",
        label: "Sign up",
        evidence: [evidence],
      },
    ],
  };
  await write(".mermaider/models/signup.json", {
    version: 1,
    review: "reviewed",
    diagram,
  });
  await write(".mermaider/config.json", {
    version: 1,
    include: ["package.json"],
    diagrams: [{ id: "signup", model: ".mermaider/models/signup.json" }],
  });
  assert.equal((await update(root)).ok, true);
  await write(
    "src/auth.ts",
    'export function signup() { return "changed"; }\n',
  );
  assert.equal((await getHookStatus(root)).current, false);
  const result = await update(root);
  assert.equal(result.ok, false);
  assert(
    result.diagnostics.some((d) =>
      d.message.includes("Semantic evidence changed"),
    ),
  );
});
test("symbol hashes are insensitive to unrelated symbols but lines follow moved declarations", async (t) => {
  const { root, write } = await fixture(t);
  await write(
    "source.ts",
    "export function stable() { return 1; }\nexport function other() { return 2; }\n",
  );
  const a = await evidenceFor(root, "source.ts", "stable");
  await write(
    "source.ts",
    "// leading comment\nexport function stable() { return 1; }\nexport function other() { return 3; }\n",
  );
  const b = await evidenceFor(root, "source.ts", "stable");
  assert.equal(a.sha256, b.sha256);
  assert.equal(b.line, 2);
});
