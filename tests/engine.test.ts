test("configuration changes during generation invalidate the candidate before publication", async (t) => {
  const { root, write } = await fixture(t);
  await initialize(root, { families: ["dependencies"] });
  const original = fs.readFile;
  let changed = false;
  (fs as any).readFile = async (...args: any[]) => {
    if (
      String(args[0]) === path.join(root, ".mermaider/manifest.json") &&
      !changed
    ) {
      changed = true;
      const config = JSON.parse(
        await original(path.join(root, ".mermaider/config.json"), "utf8"),
      );
      config.outputDir = "different-docs";
      await write(".mermaider/config.json", config);
    }
    return (original as any)(...args);
  };
  try {
    await assert.rejects(update(root), /configuration changed during analysis/);
  } finally {
    fs.readFile = original;
  }
  await assert.rejects(fs.access(path.join(root, "docs/mermaider/index.html")));
});
