test("missing sources, unreviewed models and dangling edges never certify success", async (t) => {
  const { root, write } = await fixture(t);
  await write("source.ts", "export const state = 1;");
  const evidence = await evidenceFor(root, "source.ts");
  const model = {
    version: 1,
    review: "proposed",
    diagram: {
      id: "x",
      title: "x",
      family: "process",
      syntax: "flowchart",
      provenance: "curated",
      context: "implemented",
      nodes: [{ id: "a", label: "a", evidence: [evidence] }],
      edges: [{ id: "bad", from: "a", to: "missing", evidence: [evidence] }],
    },
  };
  await write(".mermaider/models/x.json", model);
  await write(".mermaider/config.json", {
    version: 1,
    diagrams: [{ id: "x", model: ".mermaider/models/x.json" }],
  });
  assert.equal((await update(root)).ok, false);
  model.review = "reviewed";
  await write(".mermaider/models/x.json", model);
  assert(
    (await update(root)).diagnostics.some((d) => d.code === "DANGLING_EDGE"),
  );
  await fs.unlink(path.join(root, "source.ts"));
  await assert.rejects(update(root));
  assert.equal((await getHookStatus(root)).current, false);
});
